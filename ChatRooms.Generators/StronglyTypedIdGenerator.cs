using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace ChatRooms.Generators;

[Generator]
public sealed class StronglyTypedIdGenerator : IIncrementalGenerator
{
    private const string AttributeText = @"// <auto-generated/>
#nullable enable
namespace ChatRooms.Domain.Shared
{
    [global::System.AttributeUsage(global::System.AttributeTargets.Struct, Inherited = false, AllowMultiple = false)]
    internal sealed class StronglyTypedIdAttribute : global::System.Attribute
    {
    }
}
";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx => ctx.AddSource(
            "StronglyTypedIdAttribute.g.cs",
            SourceText.From(AttributeText, Encoding.UTF8)));

        var provider = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: (s, _) => s is StructDeclarationSyntax { AttributeLists.Count: > 0 } || s is RecordDeclarationSyntax { AttributeLists.Count: > 0 },
                transform: GetSemanticTargetForGeneration)
            .Where(t => t != null);

        context.RegisterSourceOutput(provider, (ctx, structSymbol) =>
        {
            if (structSymbol is null) return;
            GenerateCode(ctx, structSymbol);
        });
    }

    private static INamedTypeSymbol? GetSemanticTargetForGeneration(GeneratorSyntaxContext context, System.Threading.CancellationToken ct)
    {
        var declarationSyntax = (TypeDeclarationSyntax)context.Node;
        var symbol = context.SemanticModel.GetDeclaredSymbol(declarationSyntax, ct) as INamedTypeSymbol;
        if (symbol is null) return null;

        foreach (var attributeData in symbol.GetAttributes())
        {
            if (attributeData.AttributeClass?.Name == "StronglyTypedIdAttribute")
            {
                return symbol;
            }
        }

        return null;
    }

    private static void GenerateCode(SourceProductionContext context, INamedTypeSymbol structSymbol)
    {
        var namespaceName = structSymbol.ContainingNamespace.ToDisplayString();
        var structName = structSymbol.Name;

        var source = $@"// <auto-generated/>
#nullable enable
namespace {namespaceName}
{{
    public readonly partial record struct {structName} : global::System.IComparable<{structName}>, global::System.IEquatable<{structName}>
    {{
        public global::System.Guid Value {{ get; }}

        public {structName}(global::System.Guid value)
        {{
            if (value == global::System.Guid.Empty)
                throw new global::System.ArgumentException(""{structName} cannot be empty."");

            Value = value;
        }}

        public static {structName} New() => new(global::System.Guid.NewGuid());

        public static {structName} From(global::System.Guid value) => new(value);

        public static implicit operator global::System.Guid({structName} id) => id.Value;

        public static implicit operator {structName}(global::System.Guid value) => From(value);

        public override string ToString() => Value.ToString();

        public string ToInvariantString() => Value.ToString();

        public int CompareTo({structName} other) => Value.CompareTo(other.Value);

        public bool Equals({structName} other) => Value.Equals(other.Value);

        public override int GetHashCode() => Value.GetHashCode();
    }}
}}
";

        context.AddSource($"{structName}.g.cs", SourceText.From(source, Encoding.UTF8));
    }
}
